// Flat compressed cache rows (as the DMA left them in VTCM) straight into the F16 HMX tiles of flash
// attention, like the Q8_0 prep of hmx-q8-prep.h. K and V choose their decoder independently.
// The staging keeps 128 readable bytes after the last row: each decode loads one vector.

// ---- F8_E4M3: two blocks (64 values) per load -------------------------------------------------------
static inline HVX_Vector hmx_f8x2_f16(const uint8_t * src) {
    const HVX_Vector h    = Q6_V_lo_W(Q6_Wuh_vunpack_Vub(*(const HVX_UVector *) src));
    const HVX_Vector a    = Q6_V_vand_VV(h, Q6_Vh_vsplat_R(127));
    const HVX_Vector sign = Q6_Vh_vasl_VhR(Q6_V_vand_VV(h, Q6_Vh_vsplat_R(128)), 8);
    // normal: exponent bias 7 -> 15; subnormal (a < 8): a * 2^-9; a = 127: NaN
    HVX_Vector r = Q6_Vh_vadd_VhVh(Q6_Vh_vasl_VhR(a, 7), Q6_Vh_vsplat_R(0x2000));
    const HVX_Vector sub = Q6_Vhf_equals_Wqf32(Q6_Wqf32_vmpy_VhfVhf(Q6_Vhf_equals_Vh(a), Q6_Vh_vsplat_R(0x1800)));
    r = Q6_V_vmux_QVV(Q6_Q_vcmp_gt_VhVh(Q6_Vh_vsplat_R(8), a), sub, r);
    r = Q6_V_vmux_QVV(Q6_Q_vcmp_eq_VhVh(a, Q6_Vh_vsplat_R(127)), Q6_Vh_vsplat_R(0x7e00), r);
    return Q6_V_vor_VV(r, sign);
}

static inline HVX_Vector hmx_f8x1_f16(const uint8_t * src, HVX_VectorPred lo) {
    return Q6_V_vmux_QVV(lo, hmx_f8x2_f16(src), Q6_V_vzero());
}

// HVX-only FA staging rows: expand in place, last pair first.
static void hmx_f8_row_to_f16(void * dst, const void * src, uint32_t dim) {
    for (int c = (int) ((dim - 1) / 64) * 64; c >= 0; c -= 64) {
        hvx_vec_store_u((__fp16 *) dst + c, MIN(64u, dim - c) * 2, hmx_f8x2_f16((const uint8_t *) src + c));
    }
}

// One F8 vector of columns c .. c + 63 of a row: kind 2 = all columns, 1 = the first 32, 0 = none.
static inline __attribute__((always_inline)) HVX_Vector hmx_f8_cols(const uint8_t * s, int kind) {
    return kind == 2 ? hmx_f8x2_f16(s) : kind == 1 ? hmx_f8x1_f16(s, Q6_Q_vsetq_R(64)) : Q6_V_vzero();
}

static inline __attribute__((always_inline)) void hmx_f8_k_cols(__fp16 * tcol, const uint8_t * col, size_t stride,
                                                                size_t tstride, uint32_t start, uint32_t end2,
                                                                uint32_t end, const int kind) {
    const HVX_Vector offsets = hvx_vmem(hmx_transpose_scatter_offsets);
    uint32_t         r       = start;
    for (; r + 4 <= end2; r += 4) {
        const uint8_t *  s0 = col + (size_t) r * stride;
        const HVX_Vector a0 = hmx_f8_cols(s0, kind), a1 = hmx_f8_cols(s0 + stride, kind);
        const HVX_Vector b0 = hmx_f8_cols(s0 + 2 * stride, kind), b1 = hmx_f8_cols(s0 + 3 * stride, kind);
        const HVX_Vector oa = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
        const HVX_Vector ob = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R(((r + 2) % 32) * 4));
        const size_t     ta = (size_t) (tcol + (size_t) (r / 32) * tstride);
        const size_t     tb = (size_t) (tcol + (size_t) ((r + 2) / 32) * tstride);
        Q6_vscatter_RMVwV(ta, 4095, oa, a0);
        Q6_vscatter_RMVwV(ta, 4095, Q6_Vw_vadd_VwVw(oa, Q6_V_vsplat_R(4)), a1);
        Q6_vscatter_RMVwV(tb, 4095, ob, b0);
        Q6_vscatter_RMVwV(tb, 4095, Q6_Vw_vadd_VwVw(ob, Q6_V_vsplat_R(4)), b1);
    }
    for (; r < end; r += 2) {
        const HVX_Vector o0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
        const size_t     t  = (size_t) (tcol + (size_t) (r / 32) * tstride);
        Q6_vscatter_RMVwV(t, 4095, o0, hmx_f8_cols(col + (size_t) r * stride, kind));
        Q6_vscatter_RMVwV(t, 4095, Q6_Vw_vadd_VwVw(o0, Q6_V_vsplat_R(4)),
                          r + 1 < end ? hmx_f8_cols(col + (size_t) (r + 1) * stride, kind) : Q6_V_vzero());
    }
}

// start is even; callers partition work in row pairs. K uses word scatters: the caller completes
// them before HMX reads the tiles.
static void hmx_f8_k_to_tiles(__fp16 * dst, const uint8_t * src, size_t stride, uint32_t dim, uint32_t padded,
                              uint32_t start, uint32_t end) {
    assert(dim % 32 == 0 && padded % 64 == 0 && start % 2 == 0);
    const uint32_t end2    = start + ((end - start) & ~1u);
    const size_t   tstride = (size_t) (padded / 32) * 1024;
    for (uint32_t c = 0; c < padded; c += 64) {
        __fp16 * tcol = dst + (size_t) (c / 32) * 1024;
        if (c + 64 <= dim) {
            hmx_f8_k_cols(tcol, src + c, stride, tstride, start, end2, end, 2);
        } else if (c < dim) {
            hmx_f8_k_cols(tcol, src + c, stride, tstride, start, end2, end, 1);
        } else {
            hmx_f8_k_cols(tcol, src + c, stride, tstride, start, end2, end, 0);
        }
    }
}

static inline __attribute__((always_inline)) void hmx_f8_v_cols(__fp16 * tcol, const uint8_t * col, size_t stride,
                                                                size_t t1o, uint32_t start, uint32_t end, const int kind) {
    const uint32_t end2 = start + ((end - start) & ~1u);
    uint32_t       r    = start;
    for (; r + 4 <= end2; r += 4) {
        const uint8_t *      s0 = col + (size_t) r * stride;
        const HVX_VectorPair pa = Q6_W_vshuff_VVR(hmx_f8_cols(s0 + stride, kind), hmx_f8_cols(s0, kind), -2);
        const HVX_VectorPair pb = Q6_W_vshuff_VVR(hmx_f8_cols(s0 + 3 * stride, kind), hmx_f8_cols(s0 + 2 * stride, kind), -2);
        HVX_Vector * ta = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
        HVX_Vector * tb = (HVX_Vector *) (tcol + (size_t) ((r + 2) / 32) * 1024) + ((r + 2) % 32) / 2;
        ta[0] = Q6_V_lo_W(pa);
        *(HVX_Vector *) ((__fp16 *) ta + t1o) = Q6_V_hi_W(pa);
        tb[0] = Q6_V_lo_W(pb);
        *(HVX_Vector *) ((__fp16 *) tb + t1o) = Q6_V_hi_W(pb);
    }
    for (; r < end; r += 2) {
        const uint8_t *      s0   = col + (size_t) r * stride;
        const HVX_Vector     v1   = r + 1 < end ? hmx_f8_cols(s0 + stride, kind) : Q6_V_vzero();
        const HVX_VectorPair pair = Q6_W_vshuff_VVR(v1, hmx_f8_cols(s0, kind), -2);
        HVX_Vector * t0 = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
        t0[0] = Q6_V_lo_W(pair);
        *(HVX_Vector *) ((__fp16 *) t0 + t1o) = Q6_V_hi_W(pair);
    }
}

// V interleaves adjacent token rows. row_tiles is the allocated Bc stride, including at the final,
// partial KV block.
static void hmx_f8_v_to_tiles(__fp16 * dst, const uint8_t * src, size_t stride, uint32_t dim, uint32_t padded,
                              uint32_t row_tiles, uint32_t start, uint32_t end) {
    assert(dim % 32 == 0 && padded % 64 == 0 && start % 2 == 0);
    const size_t t1o = (size_t) row_tiles * 1024;
    for (uint32_t c = 0; c < padded; c += 64) {
        __fp16 * tcol = dst + (size_t) (c / 32) * row_tiles * 1024;
        if (c + 64 <= dim) {
            hmx_f8_v_cols(tcol, src + c, stride, t1o, start, end, 2);
        } else if (c < dim) {
            hmx_f8_v_cols(tcol, src + c, stride, t1o, start, end, 1);
        } else {
            hmx_f8_v_cols(tcol, src + c, stride, t1o, start, end, 0);
        }
    }
}

