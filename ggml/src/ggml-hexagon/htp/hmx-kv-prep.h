struct hmx_kv_decoder {
    int type;
    uint32_t pair_bytes;
    HVX_Vector codes, scale, min, high;
};

static inline struct hmx_kv_decoder hmx_kv_decoder_init(int type) {
    struct hmx_kv_decoder d;
    memset(&d, 0, sizeof(d));
    d.type = type;
    switch (type) {
#define HMX_KV_DECODER(T, t, n) case HTP_TYPE_##T: \
    d.pair_bytes = 2 * (n); d.codes = hvx_vmem(hmx_kv_##t##_codes); \
    d.scale = hvx_vmem(hmx_kv_##t##_scale); break
        HMX_KV_DECODER(Q4_0, q4_0, 18);
        HMX_KV_DECODER(Q4_1, q4_1, 20);
        HMX_KV_DECODER(Q5_0, q5_0, 22);
        HMX_KV_DECODER(Q5_1, q5_1, 24);
        case HTP_TYPE_IQ4_NL:
            d.pair_bytes = 36; d.codes = hvx_vmem(hmx_kv_q4_0_codes);
            d.scale = hvx_vmem(hmx_kv_q4_0_scale); break;
        case HTP_TYPE_F8_E4M3: d.pair_bytes = 64; break;
        default: assert(0);
#undef HMX_KV_DECODER
    }
    if (type == HTP_TYPE_Q4_1) d.min = hvx_vmem(hmx_kv_q4_1_min);
    if (type == HTP_TYPE_Q5_1) d.min = hvx_vmem(hmx_kv_q5_1_min);
    if (type == HTP_TYPE_Q5_0) d.high = hvx_vmem(hmx_kv_q5_0_high);
    if (type == HTP_TYPE_Q5_1) d.high = hvx_vmem(hmx_kv_q5_1_high);
    return d;
}

static inline HVX_Vector hmx_kvx2_f16(const uint8_t * src, const struct hmx_kv_decoder * d) {
    const HVX_Vector v = *(const HVX_UVector *) src;
    if (d->type == HTP_TYPE_F8_E4M3) {
        const HVX_Vector h = Q6_V_lo_W(Q6_Wuh_vunpack_Vub(v));
        const HVX_Vector a = Q6_V_vand_VV(h, Q6_Vh_vsplat_R(127));
        const HVX_Vector sign = Q6_Vh_vasl_VhR(Q6_V_vand_VV(h, Q6_Vh_vsplat_R(128)), 8);
        HVX_Vector r = Q6_Vh_vadd_VhVh(Q6_Vh_vasl_VhR(a, 7), Q6_Vh_vsplat_R(0x2000));
        const HVX_Vector sub = Q6_Vhf_equals_Wqf32(Q6_Wqf32_vmpy_VhfVhf(Q6_Vhf_equals_Vh(a), Q6_Vh_vsplat_R(0x1800)));
        r = Q6_V_vmux_QVV(Q6_Q_vcmp_gt_VhVh(Q6_Vh_vsplat_R(8), a), sub, r);
        r = Q6_V_vmux_QVV(Q6_Q_vcmp_eq_VhVh(a, Q6_Vh_vsplat_R(127)), Q6_Vh_vsplat_R(0x7e00), r);
        return Q6_V_vor_VV(r, sign);
    }
    HVX_Vector q = Q6_V_vdelta_VV(v, d->codes);
    // The high nibble contains values 16..31 of each block.
    const HVX_Vector lane = Q6_V_vand_VV(hvx_vmem(hvx_iquant_lanes), Q6_Vb_vsplat_R(16));
    q = Q6_V_vmux_QVV(Q6_Q_vcmp_eq_VbVb(lane, Q6_V_vzero()), q, Q6_Vub_vlsr_VubR(q, 4));
    q = Q6_V_vand_VV(q, Q6_Vb_vsplat_R(15));
    if (d->type == HTP_TYPE_IQ4_NL) {
        q = Q6_Vb_vlut32_VbVbI(q, hvx_vmem(hmx_kv_iq4_lut), 0);
    }
    HVX_Vector code = Q6_V_lo_W(Q6_Wh_vunpack_Vb(q));
    if (d->type == HTP_TYPE_Q5_0 || d->type == HTP_TYPE_Q5_1) {
        const HVX_Vector hi = Q6_V_vdelta_VV(v, d->high);
        const HVX_Vector bits = Q6_V_vand_VV(hi, hvx_vmem(hmx_kv_high_bits));
        code = Q6_Vh_vadd_VhVh(code, Q6_V_vmux_QVV(Q6_Q_vcmp_eq_VhVh(bits, Q6_V_vzero()), Q6_V_vzero(), Q6_Vh_vsplat_R(16)));
    }
    if (d->type == HTP_TYPE_Q4_0) code = Q6_Vh_vsub_VhVh(code, Q6_Vh_vsplat_R(8));
    if (d->type == HTP_TYPE_Q5_0) code = Q6_Vh_vsub_VhVh(code, Q6_Vh_vsplat_R(16));
    HVX_VectorPair prod = Q6_Wqf32_vmpy_VhfVhf(Q6_Vhf_equals_Vh(code), Q6_V_vdelta_VV(v, d->scale));
    if (d->type == HTP_TYPE_Q4_1 || d->type == HTP_TYPE_Q5_1) {
        const HVX_VectorPair m = Q6_Wqf32_vmpy_VhfVhf(Q6_V_vdelta_VV(v, d->min), Q6_Vh_vsplat_R(0x3c00));
        prod = Q6_W_vcombine_VV(Q6_Vqf32_vadd_Vqf32Vqf32(Q6_V_hi_W(prod), Q6_V_hi_W(m)),
                               Q6_Vqf32_vadd_Vqf32Vqf32(Q6_V_lo_W(prod), Q6_V_lo_W(m)));
    }
    const HVX_Vector r = Q6_Vhf_equals_Wqf32(prod);
    // Match the existing Q8 dequantizer's +0 convention.
    return Q6_V_vmux_QVV(Q6_Q_vcmp_eq_VhVh(Q6_V_vand_VV(r, Q6_Vh_vsplat_R(0x7fff)), Q6_V_vzero()), Q6_V_vzero(), r);
}

static inline HVX_Vector hmx_kvx1_f16(const uint8_t * src, const struct hmx_kv_decoder * d, HVX_VectorPred lo) {
    return Q6_V_vmux_QVV(lo, hmx_kvx2_f16(src, d), Q6_V_vzero());
}

// The HVX-only FA path uses the same decode, expanding backwards in its F16 staging row.
static inline void hmx_kv_row_to_f16(void * dst, const void * src, uint32_t dim, int type) {
    const struct hmx_kv_decoder d = hmx_kv_decoder_init(type);
    for (int c = (int) ((dim - 1) / 64) * 64; c >= 0; c -= 64) {
        const HVX_Vector r = hmx_kvx2_f16((const uint8_t *) src + (c / 64) * d.pair_bytes, &d);
        hvx_vec_store_u((__fp16 *) dst + c, MIN(64u, dim - c) * 2, r);
    }
}
// Columns c .. c + 63 (two whole blocks) of the row pairs in [r0, r1); tcol is the first tile of the
// column pair, tstride the elements of one row of tiles. The staging and the tiles do not overlap.
static inline void hmx_kv_k_pairs(__fp16 * restrict tcol, const uint8_t * restrict col, size_t stride,
                                  size_t tstride, uint32_t r0, uint32_t r1, const struct hmx_kv_decoder * dec,
                                  HVX_Vector offsets) {
    uint32_t r = r0;
    for (; r + 4 <= r1; r += 4) {
        const uint8_t *  s0 = col + (size_t) r * stride;
        const HVX_Vector a0 = hmx_kvx2_f16(s0, dec);
        const HVX_Vector a1 = hmx_kvx2_f16(s0 + stride, dec);
        const HVX_Vector b0 = hmx_kvx2_f16(s0 + 2 * stride, dec);
        const HVX_Vector b1 = hmx_kvx2_f16(s0 + 3 * stride, dec);
        const HVX_Vector oa0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
        const HVX_Vector oa1 = Q6_Vw_vadd_VwVw(oa0, Q6_V_vsplat_R(4));
        const HVX_Vector ob0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R(((r + 2) % 32) * 4));
        const HVX_Vector ob1 = Q6_Vw_vadd_VwVw(ob0, Q6_V_vsplat_R(4));
        const size_t ta = (size_t) (tcol + (size_t) (r / 32) * tstride);
        const size_t tb = (size_t) (tcol + (size_t) ((r + 2) / 32) * tstride);
        Q6_vscatter_RMVwV(ta, 4095, oa0, a0);
        Q6_vscatter_RMVwV(ta, 4095, oa1, a1);
        Q6_vscatter_RMVwV(tb, 4095, ob0, b0);
        Q6_vscatter_RMVwV(tb, 4095, ob1, b1);
    }
    for (; r < r1; r += 2) {
        const uint8_t *  s0 = col + (size_t) r * stride;
        const HVX_Vector o0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
        const HVX_Vector o1 = Q6_Vw_vadd_VwVw(o0, Q6_V_vsplat_R(4));
        const size_t     t  = (size_t) (tcol + (size_t) (r / 32) * tstride);
        Q6_vscatter_RMVwV(t, 4095, o0, hmx_kvx2_f16(s0, dec));
        Q6_vscatter_RMVwV(t, 4095, o1, hmx_kvx2_f16(s0 + stride, dec));
    }
}

// The same for V; t1o is the element offset of the second column tile of the pair.
static inline void hmx_kv_v_pairs(__fp16 * restrict tcol, const uint8_t * restrict col, size_t stride,
                                  size_t t1o, uint32_t r0, uint32_t r1, const struct hmx_kv_decoder * dec) {
    uint32_t r = r0;
    for (; r + 4 <= r1; r += 4) {
        const uint8_t *  s0 = col + (size_t) r * stride;
        const HVX_Vector a0 = hmx_kvx2_f16(s0, dec);
        const HVX_Vector a1 = hmx_kvx2_f16(s0 + stride, dec);
        const HVX_Vector b0 = hmx_kvx2_f16(s0 + 2 * stride, dec);
        const HVX_Vector b1 = hmx_kvx2_f16(s0 + 3 * stride, dec);
        const HVX_VectorPair pa = Q6_W_vshuff_VVR(a1, a0, -2);
        const HVX_VectorPair pb = Q6_W_vshuff_VVR(b1, b0, -2);
        HVX_Vector * ta = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
        HVX_Vector * tb = (HVX_Vector *) (tcol + (size_t) ((r + 2) / 32) * 1024) + ((r + 2) % 32) / 2;
        ta[0] = Q6_V_lo_W(pa);
        *(HVX_Vector *) ((__fp16 *) ta + t1o) = Q6_V_hi_W(pa);
        tb[0] = Q6_V_lo_W(pb);
        *(HVX_Vector *) ((__fp16 *) tb + t1o) = Q6_V_hi_W(pb);
    }
    for (; r < r1; r += 2) {
        const uint8_t *      s0 = col + (size_t) r * stride;
        const HVX_VectorPair pa = Q6_W_vshuff_VVR(hmx_kvx2_f16(s0 + stride, dec), hmx_kvx2_f16(s0, dec), -2);
        HVX_Vector * ta = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
        ta[0] = Q6_V_lo_W(pa);
        *(HVX_Vector *) ((__fp16 *) ta + t1o) = Q6_V_hi_W(pa);
    }
}

// start is even; callers partition work in row pairs. K uses word scatters: the caller completes
// them before HMX reads the tiles.
static inline void hmx_kv_k_to_tiles(__fp16 * dst, const uint8_t * src, size_t stride,
                                     uint32_t dim, uint32_t padded, int type, uint32_t start, uint32_t end) {
    assert(dim % 32 == 0 && padded % 64 == 0 && start % 2 == 0);
    const struct hmx_kv_decoder decoder = hmx_kv_decoder_init(type);
    const struct hmx_kv_decoder * dec = &decoder;
    const HVX_Vector     offsets = hvx_vmem(hmx_transpose_scatter_offsets);
    const HVX_VectorPred lo      = Q6_Q_vsetq_R(64);
    const uint32_t       end2    = start + ((end - start) & ~1u);
    const size_t         tstride = (size_t) (padded / 32) * 1024;
    for (uint32_t c = 0; c < padded; c += 64) {
        const uint8_t * col  = src + (size_t) (c / 64) * dec->pair_bytes;
        __fp16 *        tcol = dst + (size_t) (c / 32) * 1024;
        const int       kind = c + 64 <= dim ? 2 : c < dim ? 1 : 0;
        if (kind == 2) {
            hmx_kv_k_pairs(tcol, col, stride, tstride, start, end2, dec, offsets);
        } else {
            for (uint32_t r = start; r < end2; r += 2) {
                const HVX_Vector off0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
                const HVX_Vector off1 = Q6_Vw_vadd_VwVw(off0, Q6_V_vsplat_R(4));
                const uint8_t *  s0   = col + (size_t) r * stride;
                const HVX_Vector v0   = kind ? hmx_kvx1_f16(s0, dec, lo) : Q6_V_vzero();
                const HVX_Vector v1   = kind ? hmx_kvx1_f16(s0 + stride, dec, lo) : Q6_V_vzero();
                __fp16 *         tile = tcol + (size_t) (r / 32) * tstride;
                Q6_vscatter_RMVwV((size_t) tile, 4095, off0, v0);
                Q6_vscatter_RMVwV((size_t) tile, 4095, off1, v1);
            }
        }
        if (end2 < end) {
            const uint32_t   r    = end2;
            const HVX_Vector off0 = Q6_Vw_vadd_VwVw(offsets, Q6_V_vsplat_R((r % 32) * 4));
            const HVX_Vector off1 = Q6_Vw_vadd_VwVw(off0, Q6_V_vsplat_R(4));
            const uint8_t *  s0   = col + (size_t) r * stride;
            const HVX_Vector v0   = kind == 2 ? hmx_kvx2_f16(s0, dec) : kind == 1 ? hmx_kvx1_f16(s0, dec, lo) : Q6_V_vzero();
            __fp16 *         tile = tcol + (size_t) (r / 32) * tstride;
            Q6_vscatter_RMVwV((size_t) tile, 4095, off0, v0);
            Q6_vscatter_RMVwV((size_t) tile, 4095, off1, Q6_V_vzero());
        }
    }
}

// V interleaves adjacent token rows. row_tiles is the allocated Bc stride, including at the final,
// partial KV block.
static inline void hmx_kv_v_to_tiles(__fp16 * dst, const uint8_t * src, size_t stride,
                                     uint32_t dim, uint32_t padded, uint32_t row_tiles, int type,
                                     uint32_t start, uint32_t end) {
    assert(dim % 32 == 0 && padded % 64 == 0 && start % 2 == 0);
    const struct hmx_kv_decoder decoder = hmx_kv_decoder_init(type);
    const struct hmx_kv_decoder * dec = &decoder;
    const HVX_VectorPred lo   = Q6_Q_vsetq_R(64);
    const uint32_t       end2 = start + ((end - start) & ~1u);
    const size_t         t1o  = (size_t) row_tiles * 1024;
    for (uint32_t c = 0; c < padded; c += 64) {
        const uint8_t * col  = src + (size_t) (c / 64) * dec->pair_bytes;
        __fp16 *        tcol = dst + (size_t) (c / 32) * row_tiles * 1024;
        const int       kind = c + 64 <= dim ? 2 : c < dim ? 1 : 0;
        if (kind == 2) {
            hmx_kv_v_pairs(tcol, col, stride, t1o, start, end2, dec);
        } else {
            for (uint32_t r = start; r < end2; r += 2) {
                const uint8_t *      s0   = col + (size_t) r * stride;
                const HVX_Vector     v0   = kind ? hmx_kvx1_f16(s0, dec, lo) : Q6_V_vzero();
                const HVX_Vector     v1   = kind ? hmx_kvx1_f16(s0 + stride, dec, lo) : Q6_V_vzero();
                const HVX_VectorPair pair = Q6_W_vshuff_VVR(v1, v0, -2);
                HVX_Vector * t0 = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
                t0[0] = Q6_V_lo_W(pair);
                *(HVX_Vector *) ((__fp16 *) t0 + t1o) = Q6_V_hi_W(pair);
            }
        }
        if (end2 < end) {
            const uint32_t       r    = end2;
            const uint8_t *      s0   = col + (size_t) r * stride;
            const HVX_Vector     v0   = kind == 2 ? hmx_kvx2_f16(s0, dec) : kind == 1 ? hmx_kvx1_f16(s0, dec, lo) : Q6_V_vzero();
            const HVX_VectorPair pair = Q6_W_vshuff_VVR(Q6_V_vzero(), v0, -2);
            HVX_Vector * t0 = (HVX_Vector *) (tcol + (size_t) (r / 32) * 1024) + (r % 32) / 2;
            t0[0] = Q6_V_lo_W(pair);
            *(HVX_Vector *) ((__fp16 *) t0 + t1o) = Q6_V_hi_W(pair);
        }
    }
}


